import assert from 'node:assert/strict';
import {createDefaultState,applyEffects,validateState} from '../js/core/state.js';
import {buildPhoneModel,renderPhone} from '../js/ui/phone.js';
import {createRenderer,showStatChanges} from '../js/ui/render.js';
import {fastForward} from '../js/systems/timeline.js';
let s=createDefaultState();s.finances.cash=1000;
for(let i=0;i<65;i++)s=applyEffects(s,{cash:i%2?10:-5},{source:'check',label:'Movement '+i}).state;
assert.equal(s.finances.transactions.length,65,'bank keeps all new recorded transactions');
assert.equal(validateState(s).finances.transactions.length,65,'history survives reload');
const bank=buildPhoneModel(s).apps.find(app=>app.id==='bank');assert.ok(bank,'Bank app exists');
const html=renderPhone(buildPhoneModel(s),{open:true,activeApp:'bank'});
assert.match(html,/Current balance/);assert.match(html,/Income/);assert.match(html,/Expenses/);
assert.match(html,/Movement 0/);assert.match(html,/Movement 64/);
s.settings.phone.app='bank';assert.equal(validateState(s).settings.phone.app,'bank');
const root={innerHTML:'',addEventListener(){},removeEventListener(){},querySelector(){return null;}};
createRenderer({root,dispatch(){}}).render(s,{});
assert.match(root.innerHTML,/data-stat="health"/);assert.match(root.innerHTML,/stat-icon/);assert.match(root.innerHTML,/stat-value/);assert.match(root.innerHTML,/stat-feedback/);
s.dailyState.phase='complete';s.dailyState.complete=true;
const skipped=fastForward(s,7,{random:()=>.5});
assert.equal(skipped.summary.before.age,s.calendar.age);
assert.equal(skipped.summary.after.cash,skipped.state.finances.cash);
assert.deepEqual(skipped.summary.after.stats,skipped.state.stats);
const popups=[];
const feedbackRoot={ownerDocument:{createElement(){return {remove(){this.removed=true;},animate(frames,options){this.frames=frames;this.options=options;return this.animation={};}};}},querySelector(){return {appendChild(node){popups.push(node);}};}};
showStatChanges(feedbackRoot,{health:60,energy:70},{health:65,energy:68});
assert.deepEqual(popups.map(node=>node.textContent),['-2','+5']);
assert.match(popups[1].frames.at(-1).transform,/scale\(\.45\)/);
popups[1].animation.onfinish();assert.equal(popups[1].removed,true);
console.log('compact stats, full recorded bank history and skip snapshots passed');
