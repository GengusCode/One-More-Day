import assert from 'node:assert/strict';
import {createDefaultState,validateState} from '../js/core/state.js';
import {startBusiness,hireEmployee,expandBusiness,settleBusinessDay} from '../js/systems/business.js';
import {resolveTravel} from '../js/systems/travel.js';
import {buildPhoneModel,renderPhone} from '../js/ui/phone.js';
let s=startBusiness(createDefaultState(),'moving-service');s.finances.cash=100000;
assert.equal(hireEmployee(s,'manager').ok,false);
s=hireEmployee(s,'helper').state;s=hireEmployee(s,'helper').state;s=expandBusiness(s).state;s=hireEmployee(s,'helper').state;
const managed=hireEmployee(s,'manager');assert.equal(managed.ok,true,'established site can hire one manager');
assert.equal(hireEmployee(managed.state,'manager').ok,false,'only one manager');
assert.deepEqual(validateState(managed.state).business.staff,managed.state.business.staff);
const unstaffed=settleBusinessDay(s,{ownerAway:true,random:()=>.5});
const covered=settleBusinessDay(managed.state,{ownerAway:true,random:()=>.5});
assert.ok(covered.status.gross>unstaffed.status.gross);
assert.equal(covered.status.wages,420);assert.equal(covered.state.stats.energy,managed.state.stats.energy);
const home=resolveTravel(managed.state,'stay-home',{random:()=>.5}).state;
const tx=home.finances.transactions.at(-1);assert.equal(tx.source,'business-income');assert.match(tx.label,/away/);
assert.equal(tx.breakdown.reduce((sum,row)=>sum+row.amount,0),tx.amount);
assert.ok(tx.breakdown.some(row=>row.label==='Staff wages'&&row.amount===-420));
assert.equal(settleBusinessDay(home).state.finances.cash,home.finances.cash,'absence earnings and wages settle once');
const html=renderPhone(buildPhoneModel(managed.state),{open:true,activeApp:'business'});
assert.match(html,/Your team/);assert.match(html,/data-employee-id="employee-4"/);assert.match(html,/Manager/);assert.match(html,/skilled worker/i);assert.match(html,/R420/);
console.log('business management: manager eligibility, payroll, away income, saves and roster passed');
