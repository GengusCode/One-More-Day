import assert from 'node:assert/strict';
import {createDefaultState,validateState} from '../js/core/state.js';
import * as business from '../js/systems/business.js';
import {buildPhoneModel,renderPhone} from '../js/ui/phone.js';
let s=business.startBusiness(createDefaultState(),'moving-service');s.finances.cash=150000;
assert.equal(typeof business.expandBusiness,'function');
assert.equal(business.expandBusiness(s).ok,false,'expansion needs an established team');
s=business.hireEmployee(s,'helper').state;s=business.hireEmployee(s,'helper').state;
const before=business.getStaffLimit(s),oldSales=business.settleBusinessDay(s,{random:()=>.5}).status.gross;
assert.equal(business.expandBusiness({...s,finances:{...s.finances,cash:29999}}).ok,false);
assert.equal(business.expandBusiness({...s,business:{...s.business,trust:54}}).ok,false);
let result=business.expandBusiness(s);assert.equal(result.ok,true);s=result.state;
assert.equal(s.finances.cash,120000);assert.equal(business.getStaffLimit(s),before+3);
assert.equal(s.business.premises.length,1);assert.ok(business.settleBusinessDay(s,{random:()=>.5}).status.gross>oldSales);
assert.equal(s.finances.transactions.at(-1).label,'Open commercial premises');
assert.deepEqual(validateState(s).business.premises,s.business.premises);
assert.equal(business.expandBusiness(s).ok,false,'second branch needs four staff');
while(s.business.staff.length<4)s=business.hireEmployee(s,'helper').state;
s=business.expandBusiness(s).state;assert.equal(s.business.premises.length,2);assert.equal(s.finances.cash,45000);
assert.equal(business.getStaffLimit(s),before+6);assert.equal(business.expandBusiness(s).ok,false);
assert.match(renderPhone(buildPhoneModel(s),{open:true,activeApp:'business'}),/Commercial premises/);
assert.equal(business.expandBusiness({...s,business:{...s.business,active:false}}).ok,false);
console.log('business expansion: eligibility, costs, staff slots, revenue and save/load passed');
