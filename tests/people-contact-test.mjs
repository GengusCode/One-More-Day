import assert from 'node:assert/strict';
import {createDefaultState,validateState} from '../js/core/state.js';
import {contactPerson,getContactOptions} from '../js/systems/relationships.js';
import {buildPhoneModel,renderPhone} from '../js/ui/phone.js';
let s=createDefaultState();s.life.stage='adult';s.stats.energy=20;
s.relationships.people.mentor={id:'mentor',name:'Lebo',type:'mentor',score:58,trait:'patient'};
const before=structuredClone(s);
const reply=contactPerson(s,'mentor','catch-up');
assert.equal(reply.ok,true);assert.equal(reply.state.stats.energy,12);
assert.equal(reply.state.relationships.people.mentor.score,64);
assert.equal(reply.state.finances.cash,s.finances.cash);assert.deepEqual(s,before,'input unchanged');
assert.match(reply.message,/Lebo/);
const saved=validateState(reply.state);
assert.equal(saved.relationships.people.mentor.lastContactDay,s.calendar.day);
assert.equal(saved.relationships.people.mentor.lastReply,reply.message);
assert.equal(contactPerson(saved,'mentor','check-in').ok,false,'reload cannot bypass cooldown');
assert.ok(getContactOptions(saved,'mentor').every(option=>option.disabled));
saved.calendar.day++;assert.equal(contactPerson(saved,'mentor','check-in').ok,true);
s.stats.energy=1;assert.equal(contactPerson(s,'mentor','catch-up').ok,false);
assert.equal(contactPerson(s,'missing','check-in').ok,false);
assert.equal(contactPerson(s,'mentor','fake').ok,false);
s.life.ended=true;assert.equal(contactPerson(s,'mentor','check-in').ok,false);
const html=renderPhone(buildPhoneModel(saved),{open:true,activeApp:'people'});
assert.match(html,/CONTACT_PERSON/);assert.match(html,/Catch up/);assert.match(html,/Close/);assert.ok(html.includes(reply.message));
console.log('People contacts: costs, cooldown, saved reply, invalid actions and phone controls passed');
