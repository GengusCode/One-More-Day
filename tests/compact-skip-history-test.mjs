import assert from 'node:assert/strict';
import {createDefaultState} from '../js/core/state.js';
import {groupSkipHistory,createRenderer} from '../js/ui/render.js';
import {settleRoutineDay} from '../js/systems/day.js';
import {startCareer} from '../js/systems/career.js';
import {WORK_DECISIONS} from '../js/data/events.js';
const rows=Array.from({length:261},(_,i)=>({day:i+1,title:'Routine task',choice:'Check it',result:'Done.'}));
const groups=groupSkipHistory(rows,'choices');assert.equal(groups.length,1);assert.equal(groups[0].count,261);assert.equal(groups[0].firstDay,1);assert.equal(groups[0].lastDay,261);
const s=startCareer(createDefaultState(),'office');s.finances.cash=10000;s.dailyState.phase='complete';s.dailyState.complete=true;
assert.equal(settleRoutineDay(s,{random:()=>.99}).automaticChoice,null,'ordinary days need no special choice');
const varied={...structuredClone(s),eventDecks:{...s.eventDecks,'work-career':{order:['career-credit',...WORK_DECISIONS.filter(row=>row.path==='career'&&row.id!=='career-credit').map(row=>row.id)],seen:[]}}};
const first=settleRoutineDay(varied,{random:()=>0}).automaticChoice;
let calls=0;const second=settleRoutineDay(varied,{random:()=>calls++===0?0:.99}).automaticChoice;
assert.notEqual(first.choice,second.choice,'autopilot varies suitable answers');
s.timeline.lastSummary={before:{age:18,cash:10000,stats:{...s.stats}},after:{age:19,cash:11000,stats:{...s.stats}},requestedDays:365,daysAdvanced:365,endDay:s.calendar.day,automaticChoices:rows,milestones:rows.map(row=>({day:row.day,reason:'follow-up',text:'Same report'}))};
const root={innerHTML:'',addEventListener(){},removeEventListener(){},querySelector(){return null;}};
createRenderer({root,dispatch(){}}).render(s,{});
assert.ok(root.innerHTML.length<14000,'year report has bounded grouped markup');
assert.equal((root.innerHTML.match(/class="skip-history-group"/g)||[]).length,2,'one group for choices and one for repeated reports');
assert.match(root.innerHTML,/×261/);
console.log('compact year history: grouping, counts, dates and quieter workdays passed');
