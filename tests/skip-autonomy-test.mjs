import assert from 'node:assert/strict';
import {createDefaultState,validateState} from '../js/core/state.js';
import {startCareer} from '../js/systems/career.js';
import {startBusiness} from '../js/systems/business.js';
import {fastForward} from '../js/systems/timeline.js';
import {resolveWork} from '../js/systems/day.js';
const ready=()=>{const s=createDefaultState();s.finances.cash=10000;s.dailyState.phase='complete';s.dailyState.complete=true;return s;};
const worker=startCareer(ready(),'office');
const skipped=fastForward(worker,7,{random:()=>.5});
assert.equal(skipped.summary.daysAdvanced,7);
assert.equal(skipped.summary.automaticChoices.length,5,'ordinary work decisions resolve during weekday skips');
assert.ok(skipped.state.career.recentDecisionIds.length>=5);
assert.ok(skipped.summary.automaticChoices.every(row=>row.day>worker.calendar.day && row.choice));
assert.deepEqual(validateState(skipped.state).timeline.lastSummary.automaticChoices,skipped.summary.automaticChoices);
const owner=startBusiness(ready(),'car-wash');
owner.eventDecks['work-business']={order:['owner-warranty'],seen:[]};
const owned=fastForward(owner,7,{random:()=>.5});
assert.ok(owned.summary.automaticChoices.some(row=>row.choice==='Inspect it and explain what you can cover'),'auto routine avoids discretionary spending');
assert.ok(owned.summary.daysAdvanced>1,'a routine automatic report does not stop time');
const birthday=ready();birthday.life.ageDays=364;
const stopped=fastForward(birthday,7,{random:()=>.5});assert.equal(stopped.summary.reason,'birthday');
assert.equal(stopped.summary.remainingDays,6);
const motorist=startCareer(ready(),'office');motorist.transport.owned=['car'];motorist.transport.car={roadworthy:true,damage:0};motorist.transport.preferredVehicleId='car';motorist.garage.parking=[{id:'car',location:'home'}];
const drove=fastForward(motorist,7,{random:()=>.5}).state;
assert.equal(drove.finances.transactions.filter(tx=>tx.source==='travel-car').length,5,'selected personal car used for skipped commutes');
assert.equal(drove.finances.transactions.filter(tx=>tx.source==='travel-taxi').length,0);
const purchasing=startBusiness(ready(),'car-wash');purchasing.eventDecks['work-business']={order:['owner-supplier'],seen:[]};
const paused=fastForward(purchasing,7,{random:()=>.5});assert.equal(paused.summary.reason,'decision-needed');
const resumed=resolveWork(paused.state,'small-order',{random:()=>.5});
assert.equal(resumed.finances.transactions.filter(tx=>tx.source==='travel-taxi').length,1,'resuming a paused work choice pays commute once');
console.log('skip autonomy: work choices, safe spending, reports, saved log and remaining days passed');
