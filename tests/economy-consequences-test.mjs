import assert from 'node:assert/strict';
import { createDefaultState, validateState } from '../js/core/state.js';
import { contributeStokvel, settleHouseholdDay, settleStokvelPayout } from '../js/systems/household.js';
import { resolveDueEvents, scheduleDelayedEvent } from '../js/systems/event-deck.js';
import { startBusiness, hireEmployee, settleBusinessDay } from '../js/systems/business.js';
let state = createDefaultState();
state.finances.cash = 3000;
let paid = contributeStokvel(state, 80);
assert.equal(paid.ok, true);
assert.equal(paid.state.finances.cash, 2920);
paid = contributeStokvel(validateState(paid.state), 180);
assert.equal(paid.state.finances.cash, 2820, 'top up only the unpaid balance');
assert.equal(contributeStokvel(paid.state, 180).ok, false);
assert.equal(contributeStokvel({...state, finances:{...state.finances,cash:20}},180).ok,false);
paid.state.calendar.day = 365;
let payout = settleStokvelPayout(validateState(paid.state));
assert.equal(payout.stokvel.balance, 0);
assert.equal(payout.finances.cash, 3000, 'one month returns only that contribution');
assert.equal(settleStokvelPayout(payout).finances.cash, 3000);
let household = settleHouseholdDay(state);
assert.equal(household.finances.cash, 2975);
assert.equal(settleHouseholdDay(household).finances.cash,2975);
state.calendar.day = 30;
household = settleHouseholdDay(state);
assert.equal(household.finances.cash,2525,'food and monthly housing charged together');
let debt = scheduleDelayedEvent(state,{dueDay:31,eventId:'debt',outcomeId:'debt-30',payload:{effects:{cash:-90}},severity:3});
debt = resolveDueEvents(debt,31).state;
assert.equal(debt.finances.cash,2910);
assert.equal(resolveDueEvents(debt,32).state.finances.cash,2910);
let solo = startBusiness(state,'car-wash');
const sales = settleBusinessDay(solo,{random:()=>0.5});
assert.ok(sales.status.revenue < 140,'supplies and overhead reduce sales to profit');
let large = solo;
for(let i=0;i<20;i++) large = hireEmployee(large,'helper').state;
assert.ok(settleBusinessDay(large,{random:()=>0.5}).status.revenue < 0,'unlimited hiring cannot create unlimited profit');
console.log('economy: bills, contribution persistence, annual payout and business margins passed');
let annual = createDefaultState();
annual.finances.cash = 5000;
for (let month=0;month<12;month++) {
  annual.calendar.day = 1 + Math.ceil(month * 365 / 12);
  annual = contributeStokvel(annual,180).state;
  annual = validateState(annual);
}
assert.equal(annual.stokvel.balance,2160);
annual.calendar.day = 365;
annual = settleStokvelPayout(annual);
assert.equal(annual.stokvel.lastPayout.amount,2160);
assert.equal(annual.finances.cash,5000);
let repeat = scheduleDelayedEvent(debt,{dueDay:40,eventId:'debt',outcomeId:'debt-37',payload:{effects:{cash:-90}},severity:3});
assert.equal(resolveDueEvents(repeat,40).state.finances.cash,2820,'a later decision has its own consequence');
